"""Write a C file that builds firmware into the emulator.

usage: embed-files.py OUTPUT.c FILE...

Each FILE is registered under its base name, or under "dtb/<base name>"
when it lives in a dtb directory, which is how qemu_find_file() asks for
it.  See qemu_register_embedded_files().
"""

import os
import sys


def main():
    out, files = sys.argv[1], sys.argv[2:]
    lines = ['/* Generated by scripts/embed-files.py, do not edit. */',
             '#include "qemu/osdep.h"',
             '#include "qemu/datadir.h"',
             '']
    table = []
    for i, path in enumerate(files):
        with open(path, 'rb') as f:
            data = f.read()
        name = os.path.basename(path)
        if os.path.basename(os.path.dirname(path)) == 'dtb':
            name = 'dtb/' + name
        lines.append('static const unsigned char embedded_%d[] = {' % i)
        for off in range(0, len(data), 16):
            lines.append(','.join('%d' % b for b in data[off:off + 16]) + ',')
        lines.append('};')
        table.append('    { "%s", embedded_%d, %d },' % (name, i, len(data)))
    lines.append('')
    lines.append('static const QemuEmbeddedFile embedded_files[] = {')
    lines += table
    lines.append('    { NULL, NULL, 0 }')
    lines.append('};')
    lines.append('')
    lines.append('static void __attribute__((constructor)) '
                 'embedded_files_init(void)')
    lines.append('{')
    lines.append('    qemu_register_embedded_files(embedded_files);')
    lines.append('}')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
